import { enter, expect, test } from './fixtures'

test.describe('Estoque, prótese e indicadores', () => {
  test('estoque: cadastra, dá saída até o mínimo e vê o alerta de repor', async ({ page, clinic }) => {
    await enter(page, clinic.session, '/estoque')
    await page.getByRole('button', { name: 'Novo produto' }).first().click()
    const d = page.getByRole('dialog')
    await d.getByLabel('Nome').fill('Anestésico articaína')
    await d.getByLabel('Unidade').fill('cx')
    await d.getByLabel('Estoque mínimo').fill('3')
    await d.getByLabel('Quantidade inicial').fill('5')
    await d.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.getByRole('cell', { name: 'Anestésico articaína', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Saída de Anestésico articaína' }).click()
    const m = page.getByRole('dialog')
    await m.getByLabel(/Quantidade/).fill('9')
    await m.getByRole('button', { name: 'Registrar' }).click()
    await expect(m.getByText('Só há 5 cx.')).toBeVisible()
    await m.getByLabel(/Quantidade/).fill('2')
    await expect(m.getByText(/Saldo depois: 3 cx — abaixo do mínimo/)).toBeVisible()
    await m.getByRole('button', { name: 'Registrar' }).click()
    await expect(page.getByRole('row', { name: /Anestésico articaína/ }).getByText('Repor')).toBeVisible()
    await page.getByRole('button', { name: 'Histórico de Anestésico articaína' }).click()
    await expect(page.getByRole('dialog').getByRole('cell', { name: 'Saída' })).toBeVisible()
  })

  test('prótese: cria pedido, avança etapa pelo quadro e mostra atraso', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Vilma Prótese' })
    const yesterday = new Date(Date.now() - 86400000).toLocaleDateString('en-CA')
    await clinic.call('POST', '/prosthesis', { patientId: p.id, description: 'Protocolo superior', laboratory: 'Lab Teste', dueDate: yesterday })
    await enter(page, clinic.session, '/protese')
    await expect(page.getByText('1 pedido atrasado')).toBeVisible()
    await page.getByRole('button', { name: 'Mover Vilma Prótese, Protocolo superior, para Envio' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Vilma Prótese: Envio.' })).toBeVisible()
    const envio = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: /^Envio/ }) })
    await expect(envio.getByText('Vilma Prótese')).toBeVisible()
    await envio.getByRole('button', { name: /Vilma Prótese/ }).first().click()
    const d = page.getByRole('dialog')
    await expect(d.getByRole('heading', { name: 'Histórico' })).toBeVisible()
    await expect(d.getByRole('list').getByText('Pré-laboratório')).toBeVisible()
  })

  test('prótese: novo pedido pela tela', async ({ page, clinic }) => {
    await clinic.call('POST', '/patients', { name: 'Wesley Coroa' })
    await enter(page, clinic.session, '/protese')
    await page.getByRole('button', { name: 'Novo pedido' }).first().click()
    const d = page.getByRole('dialog')
    await d.getByRole('combobox', { name: 'Paciente' }).fill('Wesley')
    await d.getByRole('option', { name: /Wesley Coroa/ }).click()
    await d.getByLabel('Trabalho').fill('Coroa metalocerâmica — 46')
    await d.getByLabel('Laboratório', { exact: true }).fill('Lab Novo')
    await d.getByRole('button', { name: 'Criar pedido' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Pedido de Wesley Coroa criado.' })).toBeVisible()
    await expect(page.getByText('Coroa metalocerâmica — 46')).toBeVisible()
  })

  test('indicadores: desempenho com gráfico e tabela; painel do dia', async ({ page, clinic }) => {
    const today = new Date().toLocaleDateString('en-CA')
    const p = await clinic.call('POST', '/patients', { name: 'Xênia Aniversário', birthDate: `1985-${today.slice(5)}` })
    await clinic.call('POST', `/patients/${p.id}/debits`, { description: 'Consulta', amountCents: 20000, firstDueDate: new Date(Date.now() - 5 * 86400000).toLocaleDateString('en-CA') })
    await enter(page, clinic.session, '/indicadores')
    await expect(page.getByText('Consultas atendidas')).toBeVisible()
    await expect(page.getByRole('img', { name: /Gráfico de barras: recebido e pago/ })).toBeVisible()
    await page.getByRole('button', { name: 'Ver em tabela' }).click()
    await expect(page.getByRole('table', { name: 'Recebido e pago por mês' })).toBeVisible()
    await page.getByRole('tab', { name: 'Painel do dia' }).click()
    await expect(page.getByRole('table', { name: 'Aniversariantes do mês' }).getByText('Hoje')).toBeVisible()
    await expect(page.getByRole('table', { name: 'Pacientes com parcelas vencidas' }).getByRole('link', { name: 'Xênia Aniversário' })).toBeVisible()
  })

  test('odontograma: clique marca o dente; faces pelos botões abaixo', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Yara Dentes' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos/novo`)
    const t16 = page.getByRole('button', { name: /^Dente 16(,|$)/ })
    await t16.click()
    await expect(t16).toHaveAttribute('aria-pressed', 'true')
    await expect(t16).toHaveAttribute('aria-label', /Dente 16, selecionado/)
    await page.getByRole('button', { name: /^Dente 26/ }).click()
    await page.getByRole('button', { name: 'Face oclusal do dente 26' }).click()
    await expect(page.getByRole('button', { name: /^Dente 26/ })).toHaveAttribute('aria-label', /faces oclusal selecionadas/)
    await expect(page.getByRole('button', { name: 'Face oclusal do dente 26' })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('radio', { name: 'Decíduos' }).click()
    await expect(page.getByRole('button', { name: /^Dente 55/ })).toBeVisible()
    await expect(page.getByRole('button', { name: /^Dente 56/ })).toHaveCount(0)
  })

  test('tratamento: editar dente e valor, ver histórico com quem e quando, excluir', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Zeca Edita' })
    const procs = await clinic.call('GET', '/procedures')
    const pr = procs.find((x: any) => x.scope === 'tooth')
    await clinic.call('POST', `/patients/${p.id}/treatments`, { procedureId: pr.id, professionalId: clinic.professionalId, teeth: [{ tooth: 14 }], charge: false })
    await enter(page, clinic.session, `/pacientes/${p.id}/tratamentos`)
    await page.getByRole('button', { name: new RegExp(`^Editar ${pr.name}, 14`) }).click()
    const d = page.getByRole('dialog')
    await d.getByLabel('Dente').selectOption('24')
    await d.getByLabel('Valor').click()
    await page.keyboard.press('Control+A')
    await page.keyboard.type('12345')
    await d.getByRole('button', { name: 'Salvar alterações' }).click()
    await expect(page.getByRole('status').filter({ hasText: /\(24\) salvo/ })).toBeVisible()
    await page.getByRole('button', { name: new RegExp(`^Editar ${pr.name}, 24`) }).click()
    const h = page.getByRole('dialog').getByRole('region', { name: 'Histórico' }).or(page.getByRole('dialog').locator('section', { hasText: 'Histórico' }))
    await expect(h.getByText('Editado')).toBeVisible()
    await expect(h.getByText('Dra. E2E').first()).toBeVisible()
    await expect(h.getByText(/Dente: 14 → 24/)).toBeVisible()
    await expect(h.getByText(/Valor: .*→ R\$\s123,45/)).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: 'Cancelar' }).click()
    await page.getByRole('button', { name: new RegExp(`^Excluir ${pr.name}, 24`) }).click()
    await page.getByRole('dialog', { name: /Excluir/ }).getByRole('button', { name: 'Excluir tratamento' }).click()
    await expect(page.getByRole('status').filter({ hasText: /excluído/ })).toBeVisible()
    await expect(page.getByText('Nenhum tratamento lançado')).toBeVisible()
  })

  test('menu esconde o que a pessoa não pode abrir (dentista sem estoque)', async ({ page, clinic, request }) => {
    const inv = await clinic.call('POST', '/team/invitations', { email: `d+${Date.now()}@exemplo.test`, role: 'dentist', doesAttend: true })
    const s = await (await request.post(`http://localhost:8090/api/public/invitations/${inv.token}/accept`, { data: { name: 'Dra. Zélia', password: 'senha-forte-123' } })).json()
    await enter(page, s)
    const nav = page.getByRole('navigation', { name: 'Principal' })
    await expect(nav.getByRole('link', { name: 'Prótese' })).toBeVisible()
    await expect(nav.getByRole('link', { name: 'Estoque' })).toHaveCount(0)
    await expect(nav.getByRole('link', { name: 'Financeiro' })).toBeVisible() // fin.debits_view está no padrão de dentista
  })
})
