import { enter, expect, test } from './fixtures'

test.describe('F02 Orçamento e aprovação', () => {
  test('F02-H1 monta no odontograma, salva e aprova tudo', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Igor Orçamento' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos`)
    await page.getByRole('button', { name: 'Novo orçamento' }).click()
    await page.getByRole('button', { name: /^Dente 16/ }).click()
    await page.getByLabel('Procedimento').selectOption({ label: 'Extração simples — R$ 300,00' })
    await page.getByRole('button', { name: /^Adicionar/ }).click()
    await page.getByRole('button', { name: 'Salvar orçamento' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Orçamento nº \d+ salvo/ })).toBeVisible()
    await page.getByRole('button', { name: 'Aprovar' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Aprovar tudo' }).click()
    await expect(page.getByRole('status').filter({ hasText: /aprovado: 1 tratamento e 1 parcela/ })).toBeVisible()
    await expect(page.getByText('R$ 300,00').filter({ hasNot: page.locator('li') }).first()).toBeVisible()
    const debits = await clinic.call('GET', `/patients/${p.id}/debits`)
    expect(debits.map((d: any) => d.amountCents)).toEqual([30000])
  })

  test('F02-E1 aprovação parcial recalcula total e parcelas', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Júlia Parcial' })
    const procs = await clinic.call('GET', '/procedures')
    const ext = procs.find((x: any) => x.name.startsWith('Extração'))
    await clinic.call('POST', `/patients/${p.id}/budgets`, { professionalId: clinic.professionalId, installments: 2, discountCents: 5000,
      items: [{ procedureId: ext.id, tooth: 18 }, { procedureId: ext.id, tooth: 28 }] })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos`)
    await page.getByRole('button', { name: 'Aprovar' }).click()
    const d = page.getByRole('dialog')
    await d.getByRole('checkbox', { name: /28 · Extração/ }).click()
    await expect(d.getByText('R$ 250,00')).toBeVisible() // 300 − 50
    await d.getByRole('button', { name: 'Aprovar 1 item' }).click()
    await expect(page.getByText('Aprovado em parte', { exact: true })).toBeVisible()
    const debits = await clinic.call('GET', `/patients/${p.id}/debits`)
    expect(debits.reduce((t: number, x: any) => t + x.amountCents, 0)).toBe(25000)
    expect(debits).toHaveLength(2)
  })

  test('F02-E2 desconto maior que o subtotal bloqueia salvar', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Kátia Desconto' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos/novo`)
    await page.getByRole('button', { name: /^Dente 21/ }).click()
    await page.getByLabel('Procedimento').selectOption({ label: 'Extração simples — R$ 300,00' })
    await page.getByRole('button', { name: /^Adicionar/ }).click()
    await page.getByLabel('Desconto').click()
    await page.keyboard.type('40000')
    await expect(page.getByText('Desconto maior que o total.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Salvar orçamento' })).toBeDisabled()
  })

  test('F02-E3 um procedimento em vários dentes vira um item por dente', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Lia Vários' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos/novo`)
    for (const t of [36, 37, 46]) await page.getByRole('button', { name: new RegExp(`^Dente ${t}`) }).click()
    await page.getByLabel('Procedimento').selectOption({ label: 'Extração simples — R$ 300,00' })
    await page.getByRole('button', { name: 'Adicionar (3 dentes)' }).click()
    await expect(page.getByRole('textbox', { name: /Valor de Extração/ })).toHaveCount(3)
    await expect(page.locator('dl')).toContainText('Total')
    await expect(page.locator('dl')).toContainText('900,00')
  })

  test('F02-E6 recarregar ou sair no meio não perde o orçamento (BUG-005)', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Rosa Rascunho' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos/novo`)
    await page.getByRole('button', { name: /^Dente 11/ }).click()
    await page.getByLabel('Procedimento').selectOption({ label: 'Extração simples — R$ 300,00' })
    await page.getByRole('button', { name: /^Adicionar/ }).click()
    await page.reload()
    await expect(page.getByRole('textbox', { name: /^Valor de Extração/ })).toHaveCount(1)
    await expect(page.getByText(/Recuperamos o orçamento/)).toBeVisible()
    await page.getByRole('link', { name: 'Agenda' }).click()
    await page.goto(`/pacientes/${p.id}/orcamentos/novo`)
    await expect(page.getByRole('textbox', { name: /^Valor de Extração/ })).toHaveCount(1)
    await page.getByRole('button', { name: 'Salvar orçamento' }).click()
    await expect(page.getByRole('status').filter({ hasText: /salvo/ })).toBeVisible()
    await page.goto(`/pacientes/${p.id}/orcamentos/novo`)
    await expect(page.getByRole('textbox', { name: /^Valor de/ })).toHaveCount(0)
  })

  test('F02-E7 descartar o rascunho recuperado', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Sílvio Descarta' })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos/novo`)
    await page.getByRole('button', { name: /^Dente 21/ }).click()
    await page.getByLabel('Procedimento').selectOption({ label: 'Extração simples — R$ 300,00' })
    await page.getByRole('button', { name: /^Adicionar/ }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Descartar rascunho' }).click()
    await expect(page.getByRole('textbox', { name: /^Valor de/ })).toHaveCount(0)
    await page.reload()
    await expect(page.getByText(/Recuperamos o orçamento/)).toHaveCount(0)
  })

  test('F02-E5 PDF do orçamento abre no visualizador', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Mário PDF' })
    const procs = await clinic.call('GET', '/procedures')
    await clinic.call('POST', `/patients/${p.id}/budgets`, { professionalId: clinic.professionalId, items: [{ procedureId: procs[0].id, tooth: 11 }] })
    await enter(page, clinic.session, `/pacientes/${p.id}/orcamentos`)
    const pdf = page.waitForResponse((r) => r.url().includes('/pdf') && r.status() === 200)
    await page.getByRole('button', { name: 'PDF para o paciente' }).click()
    expect((await pdf).headers()['content-type']).toContain('application/pdf')
    await expect(page.getByRole('dialog').getByRole('link', { name: /Baixar/ })).toBeVisible()
  })
})
