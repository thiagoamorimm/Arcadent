import { enter, expect, patientWithDebit, test } from './fixtures'

test.describe('F04 Receber pagamento', () => {
  test('F04-H1 recebe total com recibo e o PDF abre', async ({ page, clinic }) => {
    const { patient } = await patientWithDebit(clinic, 'Rui Recebe')
    await enter(page, clinic.session, `/pacientes/${patient.id}/debitos`)
    await page.getByRole('button', { name: 'Receber' }).click()
    const pdf = page.waitForResponse((r) => r.url().includes('/receipts/') && r.url().endsWith('/pdf'))
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmar recebimento' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Recebido R\$\s300,00 · recibo nº 1/ })).toBeVisible()
    expect((await pdf).status()).toBe(200)
    await page.getByRole('dialog').getByRole('button', { name: /Fechar/ }).first().click()
    await expect(page.getByRole('table', { name: 'Débitos do paciente' }).locator('tbody').getByText('Pago')).toBeVisible()
  })

  test('F04-E1/E2 parcial; acima do saldo é bloqueado', async ({ page, clinic }) => {
    const { patient } = await patientWithDebit(clinic, 'Sara Parcial')
    await enter(page, clinic.session, `/pacientes/${patient.id}/debitos`)
    await page.getByRole('button', { name: 'Receber' }).click()
    const d = page.getByRole('dialog')
    const valor = d.getByLabel('Valor')
    await valor.click()
    await page.keyboard.press('Control+A')
    await page.keyboard.type('40000')
    await expect(d.getByText('Máximo: R$ 300,00')).toBeVisible()
    await expect(d.getByRole('button', { name: 'Confirmar recebimento' })).toBeDisabled()
    await page.keyboard.press('Control+A')
    await page.keyboard.type('10000')
    await expect(d.getByText(/pagamento parcial/)).toBeVisible()
    await d.getByRole('checkbox', { name: 'Emitir recibo agora' }).click()
    await d.getByRole('button', { name: 'Confirmar recebimento' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Recebido R$ 100,00.' })).toBeVisible()
    await expect(page.getByText('Pago em parte')).toBeVisible()
    await expect(page.getByText('Em aberto: R$ 200,00')).toBeVisible()
  })

  test('F04-E3 duplo clique em Confirmar registra um pagamento só', async ({ page, clinic }) => {
    const { patient } = await patientWithDebit(clinic, 'Téo Duplo')
    await enter(page, clinic.session, `/pacientes/${patient.id}/debitos`)
    await page.getByRole('button', { name: 'Receber' }).click()
    const d = page.getByRole('dialog')
    await d.getByRole('checkbox', { name: 'Emitir recibo agora' }).click()
    await d.getByRole('button', { name: 'Confirmar recebimento' }).dblclick()
    await expect(page.getByRole('status').filter({ hasText: 'Recebido' }).first()).toBeVisible()
    await page.waitForTimeout(800)
    expect(await clinic.call('GET', `/patients/${patient.id}/payments`)).toHaveLength(1)
  })

  test('F04-E4 cancelar recebimento devolve o saldo', async ({ page, clinic }) => {
    const { patient } = await patientWithDebit(clinic, 'Uma Cancela')
    const [debit] = await clinic.call('GET', `/patients/${patient.id}/debits`)
    const accts = await clinic.call('GET', '/financial-accounts')
    await clinic.call('POST', `/debits/${debit.id}/payments`, { amountCents: 30000, method: 'pix', financialAccountId: accts[0].id }, { 'Idempotency-Key': `e2e-${Date.now()}` })
    await enter(page, clinic.session, `/pacientes/${patient.id}/debitos`)
    await page.getByRole('button', { name: 'Cancelar recebimento de R$ 300,00' }).click()
    await page.getByRole('dialog', { name: 'Cancelar este recebimento?' }).getByRole('button', { name: 'Cancelar recebimento' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Recebimento cancelado' })).toBeVisible()
    await expect(page.getByText('Em aberto: R$ 300,00')).toBeVisible()
  })

  test('F04-E6 recebimento aparece no fluxo de caixa do mês', async ({ page, clinic }) => {
    const { patient } = await patientWithDebit(clinic, 'Vera Caixa')
    const [debit] = await clinic.call('GET', `/patients/${patient.id}/debits`)
    const accts = await clinic.call('GET', '/financial-accounts')
    await clinic.call('POST', `/debits/${debit.id}/payments`, { amountCents: 30000, method: 'pix', financialAccountId: accts[0].id }, { 'Idempotency-Key': `e2e-${Date.now()}` })
    await enter(page, clinic.session, '/financeiro')
    await expect(page.getByText('Recebido no mês').locator('..')).toContainText('R$ 300,00')
  })
})
