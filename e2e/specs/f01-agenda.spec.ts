import { enter, expect, goDay, nextTuesday, sp, test } from './fixtures'

const day = nextTuesday()

test.describe('F01 Recepção marca consulta', () => {
  test('F01-H1 paciente novo pela célula da agenda', async ({ page, clinic }) => {
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: `Marcar ${clinic.session.userName} às 10:00` }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'Paciente' }).fill('Joana Teixeira')
    await dialog.getByRole('option', { name: /Cadastrar “Joana Teixeira”/ }).click()
    await dialog.getByLabel(/Celular/).fill('(48) 98888-1111')
    await dialog.getByRole('button', { name: 'Marcar consulta' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada: Joana Teixeira' })).toBeVisible()
    await expect(page.getByRole('button', { name: /10:00 às 10:30, Joana Teixeira/ })).toBeVisible()
    const pts = await clinic.call('GET', '/patients?q=Joana')
    expect(pts.items.map((p: any) => p.phone)).toEqual(['(48) 98888-1111'])
  })

  test('F01-E1 horário ocupado: avisa com quem e permite encaixe', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Carlos Ocupado' })
    await clinic.call('POST', '/appointments', { kind: 'consulta', patientId: p.id, professionalId: clinic.professionalId, startAt: sp(day, '10:00'), endAt: sp(day, '10:30') })
    const q = await clinic.call('POST', '/patients', { name: 'Débora Encaixe' })
    await enter(page, clinic.session)
    await goDay(page, day)
    // célula ocupada mostra a consulta; marca-se por "Agendar" escolhendo o mesmo horário
    await page.getByRole('button', { name: 'Agendar' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Data').fill(day)
    await dialog.getByLabel('Início').fill('10:00')
    await dialog.getByRole('combobox', { name: 'Paciente' }).fill('Débora')
    await dialog.getByRole('option', { name: /Débora Encaixe/ }).click()
    await dialog.getByRole('button', { name: 'Marcar consulta' }).click()
    await expect(dialog.getByRole('alert')).toContainText('Carlos Ocupado')
    await dialog.getByRole('button', { name: 'Encaixar mesmo assim' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada: Débora Encaixe' })).toBeVisible()
    const appts = await clinic.call('GET', `/appointments?from=${sp(day, '00:00')}&to=${sp(day, '23:59')}`)
    expect(appts.filter((a: any) => a.patientId === q.id && a.overlapAllowed)).toHaveLength(1)
  })

  test('F01-E2 fora do expediente avisa mas deixa marcar', async ({ page, clinic }) => {
    await clinic.call('POST', '/patients', { name: 'Eva Tarde' })
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: `Marcar ${clinic.session.userName} às 12:00` }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'Paciente' }).fill('Eva')
    await dialog.getByRole('option', { name: /Eva Tarde/ }).click()
    await expect(dialog.getByText(/Fora do horário de atendimento/)).toBeVisible()
    await dialog.getByRole('button', { name: 'Marcar consulta' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada: Eva Tarde' })).toBeVisible()
  })

  test('F01-E3 duplo clique em Marcar cria uma consulta só', async ({ page, clinic }) => {
    await clinic.call('POST', '/patients', { name: 'Fábio Duplo' })
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: `Marcar ${clinic.session.userName} às 14:00` }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'Paciente' }).fill('Fábio')
    await dialog.getByRole('option', { name: /Fábio Duplo/ }).click()
    await dialog.getByRole('button', { name: 'Marcar consulta' }).dblclick()
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada' }).first()).toBeVisible()
    await page.waitForTimeout(800)
    const appts = await clinic.call('GET', `/appointments?from=${sp(day, '00:00')}&to=${sp(day, '23:59')}`)
    expect(appts.filter((a: any) => a.patientName === 'Fábio Duplo')).toHaveLength(1)
  })

  test('F01-E4 acento e emoji salvam; nome longo demais é recusado com mensagem', async ({ page, clinic }) => {
    await enter(page, clinic.session, '/pacientes')
    await page.getByRole('button', { name: 'Novo paciente' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Nome completo').fill('Zé 😀 da Conceição')
    await dialog.getByRole('button', { name: /Salvar/ }).click()
    await expect(page.getByRole('heading', { name: 'Zé 😀 da Conceição' }).first()).toBeVisible()
    await page.goto('/pacientes')
    await page.getByRole('button', { name: 'Novo paciente' }).click()
    await page.getByRole('dialog').getByLabel('Nome completo').fill('A'.repeat(170))
    await page.getByRole('dialog').getByRole('button', { name: /Salvar/ }).click()
    await expect(page.getByRole('dialog').getByRole('alert').or(page.getByRole('status').filter({ hasText: /nome|160|caracteres/i })).first()).toBeVisible()
  })

  test('F01-E5 celular 390px: agenda e modal cabem sem rolagem lateral', async ({ page, clinic }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await enter(page, clinic.session)
    await page.getByLabel('Ir para a data').fill(day)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
    expect(overflow).toBeLessThanOrEqual(0)
    await page.getByRole('button', { name: `Marcar ${clinic.session.userName} às 09:00` }).click()
    const box = await page.getByRole('dialog').boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  })

  test('F01-E6 só teclado: Agendar, paciente, Enter', async ({ page, clinic }) => {
    await clinic.call('POST', '/patients', { name: 'Gabi Teclado' })
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: 'Agendar' }).focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByRole('combobox', { name: 'Paciente' })).toBeFocused()
    await page.keyboard.type('Gabi')
    await expect(dialog.getByRole('option', { name: /Gabi Teclado/ })).toBeVisible()
    await page.keyboard.press('Enter') // escolhe o paciente
    await page.keyboard.press('Enter') // envia o formulário
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada: Gabi Teclado' })).toBeVisible()
  })

  test('F01-N2 sem paciente não marca', async ({ page, clinic }) => {
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: `Marcar ${clinic.session.userName} às 15:00` }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Marcar consulta' }).click()
    await expect(dialog.getByText('Escolha um paciente ou cadastre um novo.')).toBeVisible()
    const appts = await clinic.call('GET', `/appointments?from=${sp(day, '00:00')}&to=${sp(day, '23:59')}`)
    expect(appts).toHaveLength(0)
  })

  test('F01-H2 duplicar consulta para a semana seguinte', async ({ page, clinic }) => {
    const p = await clinic.call('POST', '/patients', { name: 'Hugo Retorno' })
    await clinic.call('POST', '/appointments', { kind: 'consulta', patientId: p.id, professionalId: clinic.professionalId, startAt: sp(day, '16:00'), endAt: sp(day, '16:30') })
    await enter(page, clinic.session)
    await goDay(page, day)
    await page.getByRole('button', { name: /16:00 às 16:30, Hugo Retorno/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Duplicar' }).click()
    const dialog = page.getByRole('dialog', { name: 'Duplicar consulta' })
    await expect(dialog.getByText('Hugo Retorno')).toBeVisible()
    await expect(dialog.getByRole('combobox', { name: 'Paciente' })).toHaveCount(0)
    await dialog.getByRole('button', { name: 'Marcar consulta' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Consulta marcada: Hugo Retorno' })).toBeVisible()
  })
})
