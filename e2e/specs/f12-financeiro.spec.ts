import { enter, expect, test } from './fixtures'

test.describe('F12 Financeiro da clínica', () => {
  test('F12-H1 lança despesa e paga', async ({ page, clinic }) => {
    await enter(page, clinic.session, '/financeiro')
    await page.getByRole('button', { name: 'Despesa' }).click()
    const d = page.getByRole('dialog')
    await d.getByLabel('Descrição').fill('Luvas e máscaras')
    await d.getByLabel('Valor').click()
    await page.keyboard.type('12990')
    await d.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.getByRole('cell', { name: 'Luvas e máscaras', exact: true })).toBeVisible()
    await page.getByRole('row', { name: /Luvas e máscaras/ }).getByRole('button', { name: 'Pagar' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmar pagamento' }).click()
    await expect(page.getByText('Pago no mês').locator('..')).toContainText('R$ 129,90')
  })

  test('F12-H2 receita sem vínculo com recibo em nome de terceiro', async ({ page, clinic }) => {
    await enter(page, clinic.session, '/financeiro')
    await page.getByRole('button', { name: 'Receita sem vínculo' }).click()
    let d = page.getByRole('dialog')
    await d.getByLabel('Descrição').fill('Sublocação da sala 2')
    await d.getByLabel('Valor').click()
    await page.keyboard.type('80000')
    await d.getByRole('button', { name: 'Lançar receita' }).click()
    await page.getByRole('row', { name: /Sublocação da sala 2/ }).getByRole('button', { name: 'Receber' }).click()
    d = page.getByRole('dialog')
    await d.getByLabel('Em nome de').fill('Odonto Parceiros Ltda')
    await d.getByLabel('CPF ou CNPJ').fill('12.345.678/0001-90')
    await d.getByRole('button', { name: 'Confirmar recebimento' }).click()
    await expect(page.getByRole('status').filter({ hasText: /recibo nº 1/ })).toBeVisible()
    const receipts = await clinic.call('GET', '/receipts')
    expect(receipts[0].payerName).toBe('Odonto Parceiros Ltda')
  })

  test('F12-E1/E2 exporta CSV e navega entre meses', async ({ page, clinic }) => {
    await clinic.call('POST', '/expenses', { description: 'Conta de luz', amountCents: 25000, dueDate: new Date().toLocaleDateString('en-CA') })
    await enter(page, clinic.session, '/financeiro')
    const dl = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar planilha' }).click()
    expect((await dl).suggestedFilename()).toMatch(/\.csv$/)
    const title = page.locator('p[aria-live="polite"]').filter({ hasText: /de \d{4}$/ })
    const before = await title.textContent()
    await page.getByRole('button', { name: 'Próximo mês' }).click()
    await expect(title).not.toHaveText(before!)
    await page.getByRole('button', { name: 'Mês atual' }).click()
    await expect(title).toHaveText(before!)
  })
})
